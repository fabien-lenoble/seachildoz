const clientAssetRoot = '../assets/images/gallery/UNIVERS CLIENT/'

const formatAssetLabel = (value: string) => value
  .replace(/\.[^/.]+$/, '')
  .replace(/[_-]+/g, ' ')
  .replace(/\s+/g, ' ')
  .trim()

const formatProjectCategory = (value: string) => formatAssetLabel(value)
  .toLowerCase()
  .replace(/\b\w/g, letter => letter.toUpperCase())

export const getClientProjectMedia = (project: PortfolioProject): ProjectMedia[] => {
  if (!project.clientAssetPath) return []

  const assetPrefix = `${clientAssetRoot}${project.clientAssetPath}/`
  return Object.entries(clientAssetModules)
    .filter(([path]) => path.startsWith(assetPrefix) && !path.split('/').some(part => part.startsWith('._')))
    .sort(([firstPath], [secondPath]) => firstPath.localeCompare(secondPath))
    .map(([path, src]) => {
      const relativePath = path.slice(assetPrefix.length)
      const folder = relativePath.includes('/') ? relativePath.slice(0, relativePath.lastIndexOf('/')) : ''
      const fileName = relativePath.slice(relativePath.lastIndexOf('/') + 1)
      const location = folder ? `${formatAssetLabel(folder)} · ` : ''

      return {
        type: 'image',
        src,
        category: folder ? formatProjectCategory(folder.split('/')[0]) : 'Selection',
        description: `${project.title} · ${location}${formatAssetLabel(fileName)}`
      }
    })
}

